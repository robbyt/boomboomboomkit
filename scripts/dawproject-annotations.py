#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# ///
"""Extract supplementary downbeat and verified-span annotations from a .dawproject.

Usage:
  uv run scripts/dawproject-annotations.py --dawproject <file.dawproject> \\
      [--match <oa300-ground-truth.json>] --out <daw-oracle-annotations.json> [--check]

Annotation convention (Story 15.8, annotation_version "15.8.v2"). In the Bitwig
Arranger the operator slides a clip, or slips its content, so that a downbeat
verified by ear sits on an arrangement bar line, and types `bar=<N>` in the track
Comment with the 1-based ruler bar number of that bar line. The tempo warp is
left as it is, and no stretch marker is added inside the verified span.

Mapping. Bitwig saves the slide as clip offsets. For one clip,
`offset_beats = outer.time + inner.time - outer.playStart - inner.playStart`,
where `outer` is the `Clip` on the lane's `Clips` timeline and `inner` the `Clip`
that directly contains `Warps`; the sum runs over every `Clip` between the lane
and the `Warps`, which in a Bitwig export is those two. A missing `time` or
`playStart` counts as 0.0; a non-finite value skips the clip. A warp
timeline beat `c` (the `Warp@time` axis, clip content beats) plays at arrangement
beat `c + offset_beats`. Arrangement bar `N` starts at arrangement beat
`4 * (N - 1)`, so its content beat is `4 * (N - 1) - offset_beats`, and its
original-audio seconds come from linear interpolation between consecutive warps.
`loopStart`, `loopEnd`, fades, the inner clip's `contentTimeUnit` and
`Clip@duration` are ignored.

Comment grammar. Tokens are separated by `;`. `bar=<N>` or `bar=<N>-<M>` (positive
integers of at most 6 digits, 1-based arrangement bars, M > N) declares the downbeat bar and,
optionally, the last bar line of the verified span; without M the span runs to
the last arrangement bar line strictly inside the audio. `level=<quarter|half|double>`
and `unc=<low|medium|high>` are optional. Any other token is the free-text
uncertainty note. A clip whose comment has no `bar=` token is not annotated.
The record's `bar_position` is N, the arrangement bar as typed, and each
`beat_position` measure and alignment-check `bar_position` is an arrangement bar.

Each record covers only the span between the two bar lines, which must be at
least 8 bars apart. No beat outside that span is written or implied. A warp
strictly inside the span must itself sit on an arrangement bar line; it becomes
an alignment check, and two warps on the same bar line skip the clip. Clips
without the convention are omitted, one stderr line each
(`skip <audio basename>: <reason>`), and the exit code stays 0.

Each `Warps` under `Arrangement` is read once and belongs to its nearest
enclosing `Lanes[@track]`, so nested (grouped) track lanes do not repeat a clip.
The track Comment declares one downbeat, so every clip of a track that holds more
than one audio clip skips with `multiple-clips-on-track`.

`--match` joins each clip to the OA300 ground truth and takes the identifiers
from the matched row; a clip with no match is skipped. Without `--match` every
clip is a candidate and the identifiers are the audio basename. In both modes a
basename seen again after the first clip is skipped.

Exit 2 means the inputs or the output path are unusable. With `--check` nothing
is written: exit 0 when `--out` already holds the regenerated bytes, exit 1
otherwise.

The output stays operator-local next to `daw-oracle.json`; it is never committed.
"""

