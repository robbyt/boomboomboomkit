# Loading dawproject-bpm.py by path would otherwise drop a .pyc into scripts/__pycache__.
sys.dont_write_bytecode = True

ANNOTATION_VERSION = "15.8.v2"
SOURCE = "bitwig-clip-offset-bar-comment"
DATA_SOURCE = "DAW manual placement, clip offset and bar comment"

BEATS_PER_BAR = 4
BAR_TOLERANCE_BEATS = 0.02
MIN_SPAN_BARS = 8
END_OF_FILE_MARGIN_SEC = 1e-6

METRICAL_LEVELS = ("quarter", "half", "double")
UNCERTAINTY_LEVELS = ("low", "medium", "high")
DEFAULT_LEVEL = "unspecified"
DEFAULT_UNCERTAINTY_LEVEL = "medium"
NOTE_NO_FREE_TEXT = "derived from clip offset and bar comment; no free text"

SKIP_NO_BAR = "no-declared-downbeat-bar"
SKIP_BAR_OUTSIDE = "declared-bar-outside-audio"
SKIP_SHORT_SPAN = "verified-span-shorter-than-8-bars"
SKIP_UNVERIFIED_WARP = "unverified-warp-inside-span"
SKIP_NOT_MONOTONIC = "warps-not-monotonic"
SKIP_NOT_BEATS_SECONDS = "warps-not-beats-seconds"
SKIP_OFFSET = "clip-offset-not-finite"
SKIP_UNMATCHED = "unmatched-ground-truth"
SKIP_DUPLICATE = "duplicate-basename"
SKIP_INVALID_COMMENT = "invalid-comment-token"
SKIP_TIME_SIGNATURE = "time-signature-not-4-4"
SKIP_MULTIPLE_CLIPS = "multiple-clips-on-track"

BAR_VALUE = re.compile(r"([0-9]{1,6})(?:\s*-\s*([0-9]{1,6}))?")


class InputError(Exception):
    """An unusable input or output path. main() reports it on one line and exits 2."""


def _load_bpm_module() -> types.ModuleType:
    """Load the sibling `dawproject-bpm.py` for its ground-truth matching helpers."""
    path = Path(__file__).resolve().with_name("dawproject-bpm.py")
    spec = importlib.util.spec_from_file_location("dawproject_bpm", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load a module spec from {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


bpm_module = _load_bpm_module()


@dataclass(frozen=True)
class WarpPoint:
    time: float  # clip content beats
    content_time: float  # original-audio seconds


@dataclass(frozen=True)
class ClipInput:
    audio_path: str  # `File@path` as written, e.g. "audio/x.wav"
    audio_duration_raw: str
    warps_raw: tuple[tuple[str, str], ...]  # (time, contentTime) strings in document order
    beat_timeline: bool  # Warps timeUnit is beats and contentTimeUnit is seconds
    clip_offsets_raw: tuple[tuple[str, str], ...]  # (time, playStart) per enclosing Clip
    track_id: str  # `Lanes@track` of the nearest enclosing track lane
    comment: str

    @property
    def basename(self) -> str:
        return os.path.basename(self.audio_path)


@dataclass(frozen=True)
class Comment:
    level: str
    uncertainty_level: str
    note: str
    bar_start: int | None  # 1-based arrangement bar of the declared downbeat
    bar_end: int | None  # 1-based arrangement bar closing the span, when declared


# --- reading ------------------------------------------------------------------


def _required(el: ET.Element, attr: str) -> str:
    value = el.get(attr)
    if value is None:
        raise InputError(f"project.xml: <{el.tag}> is missing required attribute '{attr}'")
    return value


def read_project(dawproject_path: str) -> ET.Element:
    """Open the .dawproject zip and parse its project.xml."""
    path = Path(dawproject_path)
    if not path.is_file():
        raise InputError(f"--dawproject {dawproject_path}: no such file")
    try:
        with zipfile.ZipFile(path, "r") as zf:
            try:
                data = zf.read("project.xml")
            except KeyError:
                raise InputError(
                    f"--dawproject {dawproject_path}: zip has no project.xml"
                ) from None
    except zipfile.BadZipFile:
        raise InputError(f"--dawproject {dawproject_path}: not a zip archive") from None
    except OSError as exc:
        raise InputError(f"--dawproject {dawproject_path}: {exc.strerror or exc}") from None
    try:
        return ET.fromstring(data)
    except ET.ParseError as exc:
        raise InputError(
            f"--dawproject {dawproject_path}: project.xml parse error: {exc}"
        ) from None


def read_application(root: ET.Element) -> dict:
    app = root.find("Application")
    if app is None:
        raise InputError("project.xml: missing required element <Application>")
    return {"name": _required(app, "name"), "version": _required(app, "version")}


def is_four_four(root: ET.Element) -> bool:
    """True iff the project declares a fixed 4/4 meter with no meter automation."""
    if root.find(".//TimeSignatureAutomation") is not None:
        return False
    sig = root.find("Transport/TimeSignature")
    if sig is None:
        return False
    numerator = _required(sig, "numerator")
    denominator = _required(sig, "denominator")
    try:
        return float(numerator) == 4 and float(denominator) == 4
    except ValueError:
        return False


def _nearest_track_lanes(warps: ET.Element, parents: dict) -> ET.Element | None:
    """The nearest enclosing `Lanes` element with a `track` attribute, or None."""
    node = parents.get(warps)
    while node is not None:
        if node.tag == "Lanes" and node.get("track") is not None:
            return node
        node = parents.get(node)
    return None


def _enclosing_clips(warps: ET.Element, lanes: ET.Element, parents: dict) -> list[ET.Element]:
    """The `Clip` elements between `lanes` and `warps`, outermost first.

    For the Bitwig shape (`Lanes > Clips > Clip > Clips > Clip > Warps`) these are
    the outer clip on the lane's timeline and the inner clip holding the warps.
    """
    found: list[ET.Element] = []
    node = parents.get(warps)
    while node is not None and node is not lanes:
        if node.tag == "Clip":
            found.append(node)
        node = parents.get(node)
    found.reverse()
    return found


def collect_clips(root: ET.Element) -> list[ClipInput]:
    """Every arrangement clip with audio, once each, in document order.

    Each `Warps` under `Arrangement` belongs to its nearest enclosing
    `Lanes[@track]`, which supplies the track comment and bounds the clip offsets;
    a `Warps` with no such lane is ignored. On the flat Bitwig shape this sees the
    same clips as `dawproject-bpm.py` (`Arrangement//Lanes[@track]`, then every
    `Warps` below it); when track lanes are nested, this visits each `Warps` once,
    where that traversal would visit it once per enclosing track lane.
    """
    comments = {t.get("id"): t.get("comment", "") for t in root.iter("Track") if t.get("id")}
    clips: list[ClipInput] = []
    for arrangement in root.iter("Arrangement"):
        parents = {child: parent for parent in arrangement.iter() for child in parent}
        for warps in arrangement.iter("Warps"):
            lanes = _nearest_track_lanes(warps, parents)
            if lanes is None:
                continue
            audio = warps.find("Audio")
            if audio is None:
                continue
            file_el = audio.find("File")
            if file_el is None:
                raise InputError("project.xml: <Audio> is missing required element <File>")
            track_id = lanes.get("track", "")
            # A unit attribute may be inherited from an enclosing timeline, so only an
            # explicit non-beat or non-second unit rules the clip out.
            beat_timeline = warps.get("timeUnit", "beats") == "beats" and (
                warps.get("contentTimeUnit", "seconds") == "seconds"
            )
            clips.append(
                ClipInput(
                    audio_path=_required(file_el, "path"),
                    audio_duration_raw=_required(audio, "duration"),
                    warps_raw=tuple(
                        (_required(w, "time"), _required(w, "contentTime"))
                        for w in warps.findall("Warp")
                    ),
                    beat_timeline=beat_timeline,
                    clip_offsets_raw=tuple(
                        (c.get("time", "0.0"), c.get("playStart", "0.0"))
                        for c in _enclosing_clips(warps, lanes, parents)
                    ),
                    track_id=track_id,
                    comment=comments.get(track_id, "") or "",
                )
            )
    return clips


def load_ground_truth(match_path: str) -> list[dict]:
    """Flat OA300 rows via `dawproject-bpm.py`, validated for matching."""
    try:
        rows = bpm_module._load_oa300_rows(match_path)
    except OSError as exc:
        raise InputError(f"--match {match_path}: {exc.strerror or exc}") from None
    except (ValueError, KeyError, TypeError, AttributeError) as exc:
        raise InputError(f"--match {match_path}: invalid ground truth: {exc}") from None
    for row in rows:
        if not isinstance(row.get("filename"), str) or not row["filename"]:
            raise InputError(f"--match {match_path}: an entry has no identifiers.basename")
    return rows


# --- rules --------------------------------------------------------------------


def clean_warps(clip: ClipInput) -> tuple[list[WarpPoint], float] | None:
    """Sorted, finite, strictly increasing warps and a positive duration, or None."""
    try:
        duration = float(clip.audio_duration_raw)
        points = [WarpPoint(float(t), float(c)) for t, c in clip.warps_raw]
    except ValueError:
        return None
    if not math.isfinite(duration) or duration <= 0:
        return None
    if not all(math.isfinite(p.time) and math.isfinite(p.content_time) for p in points):
        return None
    points.sort(key=lambda p: p.time)
    for prev, cur in zip(points, points[1:]):
        if cur.time <= prev.time or cur.content_time <= prev.content_time:
            return None
    return points, duration


def clip_offset_beats(clip: ClipInput) -> float | None:
    """`sum(Clip@time - Clip@playStart)` over the enclosing clips, or None if not finite."""
    total = 0.0
    try:
        for time_raw, play_start_raw in clip.clip_offsets_raw:
            total += float(time_raw) - float(play_start_raw)
    except ValueError:
        return None
    return total if math.isfinite(total) else None


def parse_comment(raw: str) -> Comment | None:
    """Track comment tokens; None when a `bar`, `level` or `unc` token is invalid or repeated."""
    level: str | None = None
    unc: str | None = None
    bars: tuple[int, int | None] | None = None
    note_parts: list[str] = []
    for token in raw.split(";"):
        token = token.strip()
        if not token:
            continue
        key, sep, value = token.partition("=")
        key = key.strip().lower()
        value = value.strip().lower()
        if sep and key == "level":
            if value not in METRICAL_LEVELS or level is not None:
                return None
            level = value
        elif sep and key == "unc":
            if value not in UNCERTAINTY_LEVELS or unc is not None:
                return None
            unc = value
        elif sep and key == "bar":
            match = BAR_VALUE.fullmatch(value)
            if match is None or bars is not None:
                return None
            start = int(match.group(1))
            end = int(match.group(2)) if match.group(2) is not None else None
            if start < 1 or (end is not None and end <= start):
                return None
            bars = (start, end)
        else:
            note_parts.append(token)
    return Comment(
        level or DEFAULT_LEVEL,
        unc or DEFAULT_UNCERTAINTY_LEVEL,
        "; ".join(note_parts) if note_parts else NOTE_NO_FREE_TEXT,
        bars[0] if bars else None,
        bars[1] if bars else None,
    )


def seconds_at(points: list[WarpPoint], beat: float) -> float | None:
    """Original-audio seconds at a content beat, linear between warps; None off the map."""
    if len(points) < 2 or not points[0].time <= beat <= points[-1].time:
        return None
    for prev, cur in zip(points, points[1:]):
        if beat <= cur.time:
            fraction = (beat - prev.time) / (cur.time - prev.time)
            return prev.content_time + fraction * (cur.content_time - prev.content_time)
    return None


def beat_at(points: list[WarpPoint], seconds: float) -> float | None:
    """Content beat at original-audio seconds, the inverse of `seconds_at`."""
    if len(points) < 2 or not points[0].content_time <= seconds <= points[-1].content_time:
        return None
    for prev, cur in zip(points, points[1:]):
        if seconds <= cur.content_time:
            fraction = (seconds - prev.content_time) / (cur.content_time - prev.content_time)
            return prev.time + fraction * (cur.time - prev.time)
    return None


@dataclass(frozen=True)
class BarLine:
    bar: int  # 1-based arrangement bar
    beat: float  # clip content beat on the warp timeline
    seconds: float  # original-audio seconds


@dataclass(frozen=True)
class SpanAnnotation:
    duration: float
    start: BarLine
    end: BarLine
    interior: list[BarLine]  # bar-line warps strictly inside the span, in time order
    verified_bpm: float
    comment: Comment


class _BarMap:
    """Arrangement bar lines mapped through one clip's offset and warp map."""

    def __init__(self, points: list[WarpPoint], duration: float, offset_beats: float):
        self.points = points
        self.duration = duration
        self.offset_beats = offset_beats

    def content_beat(self, bar: int) -> float:
        return BEATS_PER_BAR * (bar - 1) - self.offset_beats

    def inside(self, bar: int) -> BarLine | None:
        """The bar line when its content seconds are strictly inside the audio, else None."""
        beat = self.content_beat(bar)
        seconds = seconds_at(self.points, beat)
        if seconds is None or not 0 < seconds < self.duration - END_OF_FILE_MARGIN_SEC:
            return None
        return BarLine(bar, beat, seconds)

    def last_inside(self, after: int) -> BarLine | None:
        """The last bar line after bar `after` strictly inside the audio and the warp map."""
        limit_sec = self.duration - END_OF_FILE_MARGIN_SEC
        if limit_sec >= self.points[-1].content_time:
            limit_beat: float | None = self.points[-1].time
        else:
            limit_beat = beat_at(self.points, limit_sec)
        if limit_beat is None:
            return None
        bar = math.floor((limit_beat + self.offset_beats) / BEATS_PER_BAR) + 1
        # The inverse map lands on or one bar past the boundary; step back to the first inside.
        while bar > after:
            line = self.inside(bar)
            if line is not None:
                return line
            bar -= 1
        return None

    def arrangement_bar(self, warp: WarpPoint) -> int | None:
        """The 1-based arrangement bar a warp sits on, or None when it is off every bar line."""
        bars = (warp.time + self.offset_beats) / BEATS_PER_BAR
        if abs(bars - round(bars)) * BEATS_PER_BAR > BAR_TOLERANCE_BEATS:
            return None
        return round(bars) + 1


def annotate_clip(clip: ClipInput) -> SpanAnnotation | str:
    """The verified span of one clip, or the skip reason."""
    cleaned = clean_warps(clip)
    if cleaned is None:
        return SKIP_NOT_MONOTONIC
    points, duration = cleaned
    if not clip.beat_timeline:
        return SKIP_NOT_BEATS_SECONDS
    comment = parse_comment(clip.comment)
    if comment is None:
        return SKIP_INVALID_COMMENT
    if comment.bar_start is None:
        return SKIP_NO_BAR
    offset = clip_offset_beats(clip)
    if offset is None:
        return SKIP_OFFSET
    bar_map = _BarMap(points, duration, offset)

    start = bar_map.inside(comment.bar_start)
    if start is None:
        return SKIP_BAR_OUTSIDE
    if comment.bar_end is not None:
        end = bar_map.inside(comment.bar_end)
        if end is None:
            return SKIP_BAR_OUTSIDE
    else:
        end = bar_map.last_inside(start.bar)
    if end is None or end.bar - start.bar < MIN_SPAN_BARS:
        return SKIP_SHORT_SPAN

    interior: list[BarLine] = []
    interior_bars: set[int] = set()
    for warp in points:
        if not start.beat < warp.time < end.beat:
            continue
        bar = bar_map.arrangement_bar(warp)
        if bar is None:
            return SKIP_UNVERIFIED_WARP
        # A warp within the tolerance of the start or end bar line is that bar line.
        if start.bar < bar < end.bar:
            # Two warps on one bar line are a stretch inside that bar, not one bar line.
            if bar in interior_bars:
                return SKIP_UNVERIFIED_WARP
            interior_bars.add(bar)
            interior.append(BarLine(bar, warp.time, warp.content_time))

    bpm = (end.beat - start.beat) / (end.seconds - start.seconds) * 60.0
    return SpanAnnotation(duration, start, end, interior, bpm, comment)


# --- output -------------------------------------------------------------------


def _beat_position(line: BarLine) -> dict:
    return {
        "time": line.seconds,
        "duration": 0.0,
        "value": {
            "position": 1,
            "measure": line.bar,
            "num_beats": BEATS_PER_BAR,
            "beat_units": 4,
        },
        "confidence": 1.0,
    }


def build_entry(identifiers: dict, span: SpanAnnotation, application: dict, curator: dict) -> dict:
    start, end = span.start.seconds, span.end.seconds
    checks = [
        {
            "time_sec": line.seconds,
            "bar_position": line.bar,
            "residual_ms": (
                line.seconds - (start + (line.beat - span.start.beat) * 60.0 / span.verified_bpm)
            )
            * 1000.0,
        }
        for line in span.interior
    ]
    lines = sorted([span.start, *span.interior, span.end], key=lambda line: line.seconds)
    metadata = {"curator": curator, "data_source": DATA_SOURCE}
    return {
        "file_metadata": {
            "duration": span.duration,
            "jams_version": "0.4.0",
            "identifiers": identifiers,
        },
        "annotations": [
            {
                "namespace": "tempo",
                "data": [
                    {
                        "time": start,
                        "duration": end - start,
                        "value": span.verified_bpm,
                        "confidence": 1.0,
                    }
                ],
                "annotation_metadata": metadata,
            },
            {
                "namespace": "beat_position",
                "data": [_beat_position(line) for line in lines],
                "annotation_metadata": metadata,
            },
        ],
        "sandbox": {
            "reference_downbeat_time_sec": start,
            "verified_bpm": span.verified_bpm,
            "declared_metrical_level": span.comment.level,
            "bar_position": span.start.bar,
            "verified_span_start_sec": start,
            "verified_span_end_sec": end,
            "distant_alignment_checks": checks,
            "uncertainty": {"level": span.comment.uncertainty_level, "note": span.comment.note},
            "annotation_version": ANNOTATION_VERSION,
            "source": SOURCE,
            "dawproject_application": application,
        },
    }


def _oracle_identifiers(gt_row: dict) -> dict:
    """Identifiers exactly as `_daw_oracle_to_jams` builds them, so a consumer joins on basename."""
    basename = gt_row["filename"]
    subdir = gt_row.get("subdir")
    local_path = f"{subdir}/{basename}" if subdir else basename
    return {"basename": basename, "local_path": local_path, "track_id": basename}


def generate(dawproject_path: str, match_path: str | None) -> tuple[dict, list[str]]:
    """The annotations document and the stderr skip lines, in clip document order."""
    root = read_project(dawproject_path)
    application = read_application(root)
    clips = collect_clips(root)
    gt_rows = load_ground_truth(match_path) if match_path is not None else None
    four_four = is_four_four(root)
    curator = bpm_module._curator()
    # One track Comment cannot declare a downbeat for two clips.
    clips_per_track = Counter(clip.track_id for clip in clips)

    entries: list[dict] = []
    skips: list[str] = []
    reserved: set[str] = set()
    for clip in clips:
        reason: str | None = None
        identifiers: dict | None = None
        if not four_four:
            reason = SKIP_TIME_SIGNATURE
        elif clips_per_track[clip.track_id] > 1:
            reason = SKIP_MULTIPLE_CLIPS
        elif gt_rows is None:
            identifiers = {
                "basename": clip.basename,
                "local_path": clip.basename,
                "track_id": clip.basename,
            }
        else:
            gt_row = bpm_module.find_ground_truth_match(
                bpm_module.strip_audio_prefix(clip.audio_path), gt_rows
            )
            if gt_row is None:
                reason = SKIP_UNMATCHED
            else:
                identifiers = _oracle_identifiers(gt_row)
        if identifiers is not None:
            if identifiers["basename"] in reserved:
                reason = SKIP_DUPLICATE
            else:
                # The first clip with a basename reserves it, even if it is skipped below.
                reserved.add(identifiers["basename"])
                result = annotate_clip(clip)
                if isinstance(result, str):
                    reason = result
                else:
                    entries.append(build_entry(identifiers, result, application, curator))
        if reason is not None:
            skips.append(f"skip {clip.basename}: {reason}")

    entries.sort(key=lambda e: e["file_metadata"]["identifiers"]["basename"])
    return {"entries": entries}, skips


def _round_floats(value: object) -> object:
    if isinstance(value, float):
        return round(value, 6) + 0.0  # + 0.0 folds -0.0 into 0.0
    if isinstance(value, dict):
        return {k: _round_floats(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_round_floats(v) for v in value]
    return value


def render(document: dict) -> bytes:
    text = json.dumps(_round_floats(document), sort_keys=True, indent=2, ensure_ascii=False)
    return (text + "\n").encode("utf-8")


def write_atomic(out_path: str, data: bytes) -> None:
    """Write via a temp file in the target directory and `os.replace` it into place."""
    target = Path(out_path)
    tmp_name: str | None = None
    try:
        fd, tmp_name = tempfile.mkstemp(dir=target.parent, prefix=f".{target.name}.", suffix=".tmp")
        with os.fdopen(fd, "wb") as fh:
            fh.write(data)
            fh.flush()
            os.fsync(fh.fileno())
        umask = os.umask(0)
        os.umask(umask)
        os.chmod(tmp_name, 0o666 & ~umask)
        os.replace(tmp_name, target)
        tmp_name = None
    except OSError as exc:
        raise InputError(f"--out {out_path}: cannot write: {exc.strerror or exc}") from None
    finally:
        if tmp_name is not None:
            with contextlib.suppress(OSError):
                os.unlink(tmp_name)


def check_summary(out_path: str, expected: bytes) -> str | None:
    """None when `out_path` already holds `expected`, else a one-line reason."""
    try:
        existing = Path(out_path).read_bytes()
    except FileNotFoundError:
        return f"check: {out_path} is missing"
    except OSError as exc:
        return f"check: {out_path} is unreadable: {exc.strerror or exc}"
    if existing == expected:
        return None
    try:
        old_entries = json.loads(existing)["entries"]
        new_entries = json.loads(expected)["entries"]
    except (ValueError, KeyError, TypeError):
        return f"check: {out_path} is not an annotations document"
    for old, new in zip(old_entries, new_entries):
        if old != new:
            return f"check: {out_path} differs at entry {_entry_basename(new)}"
    if len(old_entries) != len(new_entries):
        longer = old_entries if len(old_entries) > len(new_entries) else new_entries
        extra = longer[min(len(old_entries), len(new_entries))]
        return f"check: {out_path} differs at entry {_entry_basename(extra)}"
    return f"check: {out_path} differs in formatting only"


def _entry_basename(entry: Any) -> str:
    node: Any = entry
    for key in ("file_metadata", "identifiers", "basename"):
        if not isinstance(node, dict) or key not in node:
            return "<unnamed entry>"
        node = node[key]
    return str(node)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--dawproject", required=True, help="Path to the .dawproject file")
    parser.add_argument(
        "--match",
        metavar="GROUND_TRUTH_JSON",
        help="OA300 JAMS ground truth; without it, identifiers are the audio basename",
    )
    parser.add_argument("--out", required=True, help="Output path for daw-oracle-annotations.json")
    parser.add_argument(
        "--check", action="store_true", help="Compare against --out without writing"
    )
    args = parser.parse_args(argv)

    try:
        document, skips = generate(args.dawproject, args.match)
        for line in skips:
            print(line, file=sys.stderr)
        data = render(document)
        if args.check:
            summary = check_summary(args.out, data)
            if summary is not None:
                print(summary, file=sys.stderr)
                return 1
            return 0
        write_atomic(args.out, data)
    except InputError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
